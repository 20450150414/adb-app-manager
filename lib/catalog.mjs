/**
 * 按包名关键字启发式推断厂商。顺序敏感：Google 相关关键字要先于 com.android 判定，
 * 否则 com.android.vending / com.google.android.* 会被误判为 aosp。
 */
export function detectVendor(pkg) {
  const p = String(pkg ?? '').toLowerCase();
  if (/miui|xiaomi|redmi|mipay/.test(p)) return 'xiaomi';
  if (/huawei|hihonor|honor|hwid/.test(p)) return 'huawei';
  if (/oppo|coloros|oplus|oneplus|realme|heytap/.test(p)) return 'oppo';
  if (/vivo|bbk|iqoo/.test(p)) return 'vivo';
  if (/samsung|sec\.android/.test(p)) return 'samsung';
  if (/google|gms|gsf|android\.vending|\.vending/.test(p)) return 'google';
  if (p === 'android' || p.startsWith('com.android')) return 'aosp';
  return 'other';
}

/** 把包名末段整理成可读短语，供未收录条目生成 label。 */
function readableTail(pkg) {
  const tail = String(pkg).split('.').pop() || String(pkg);
  return tail.replace(/[_-]+/g, ' ').replace(/([a-z0-9])([A-Z])/g, '$1 $2').trim() || tail;
}

/**
 * 查询单个包名。命中 CATALOG 时返回其完整信息并计算 dangerous/known；
 * 未命中时用 detectVendor + 包名末段生成可读 label，risk:'unknown'、known:false、dangerous:false。
 */
export function lookup(pkg) {
  const hit = CATALOG[pkg];
  if (hit) {
    return {
      label: hit.label,
      vendor: hit.vendor,
      risk: hit.risk,
      category: hit.category,
      note: hit.note,
      dangerous: hit.risk === 'critical' || hit.risk === 'high',
      known: true,
    };
  }
  const vendor = detectVendor(pkg);
  return {
    label: `${VENDOR_LABELS[vendor] || VENDOR_LABELS.other} · ${readableTail(pkg)}`,
    vendor,
    risk: 'unknown',
    category: '未分类',
    note: '未收录的应用，卸载影响请自行确认；建议先备份数据再操作',
    dangerous: false,
    known: false,
  };
}
